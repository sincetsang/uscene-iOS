import Foundation
import Observation

enum AppLanguage: String, CaseIterable, Identifiable {
    case english = "en"
    case simplifiedChinese = "zh"
    case traditionalChinese = "zh_tw"

    var id: String { rawValue }

    var displayName: String {
        switch self {
        case .english: return "English"
        case .simplifiedChinese: return "简体中文"
        case .traditionalChinese: return "繁體中文"
        }
    }

    /// Matches RN Language header values used by the backend.
    var apiCode: String {
        switch self {
        case .english: return "en"
        case .simplifiedChinese: return "zh"
        case .traditionalChinese: return "zh_tw"
        }
    }
}

@Observable
@MainActor
final class LanguageManager {
    static let shared = LanguageManager()

    private let storageKey = "app_language"
    var language: AppLanguage

    var apiLanguageCode: String { language.apiCode }

    /// True when the user picked a language in Settings (overrides system).
    var hasManualOverride: Bool {
        UserDefaults.standard.string(forKey: storageKey) != nil
    }

    private init() {
        if let raw = UserDefaults.standard.string(forKey: storageKey),
           let lang = AppLanguage(rawValue: raw) {
            language = lang
        } else {
            language = Self.resolveSystemLanguage()
        }
    }

    /// Maps iOS system preferred languages to app languages (en / zh / zh_tw).
    nonisolated static func resolveSystemLanguage() -> AppLanguage {
        for preferred in Locale.preferredLanguages {
            let code = preferred.lowercased().replacingOccurrences(of: "_", with: "-")
            if code.hasPrefix("zh") {
                if code.contains("hant")
                    || code.hasPrefix("zh-tw")
                    || code.hasPrefix("zh-hk")
                    || code.hasPrefix("zh-mo") {
                    return .traditionalChinese
                }
                // zh-Hans, zh-CN, zh-SG, bare zh
                return .simplifiedChinese
            }
            if code.hasPrefix("en") {
                return .english
            }
        }

        if let id = Locale.current.language.languageCode?.identifier.lowercased() {
            if id == "zh" {
                if let script = Locale.current.language.script?.identifier.lowercased(), script == "hant" {
                    return .traditionalChinese
                }
                return .simplifiedChinese
            }
            if id == "en" { return .english }
        }
        return .english
    }

    func setLanguage(_ language: AppLanguage) {
        self.language = language
        UserDefaults.standard.set(language.rawValue, forKey: storageKey)
    }

    /// Clear override and follow the phone system language again.
    func followSystemLanguage() {
        UserDefaults.standard.removeObject(forKey: storageKey)
        language = Self.resolveSystemLanguage()
    }

    func t(_ key: String) -> String {
        Strings.lookup(key, language: language)
    }
}

